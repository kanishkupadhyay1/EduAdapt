import re
from typing import Dict, List, Any, Set, Tuple


def normalize_text(text: str) -> str:
    """Normalize text for strict duplicate detection."""
    if not text:
        return ""
    # Strip non-alphanumeric except spaces, lowercase, collapse whitespace
    cleaned = re.sub(r"[^\w\s]", " ", text.lower())
    return " ".join(cleaned.split())


def calculate_jaccard_similarity(text1: str, text2: str) -> float:
    """Compute token Jaccard similarity between two question statements."""
    tokens1 = set(normalize_text(text1).split())
    tokens2 = set(normalize_text(text2).split())
    if not tokens1 or not tokens2:
        return 0.0
    intersection = tokens1.intersection(tokens2)
    union = tokens1.union(tokens2)
    return len(intersection) / len(union)


