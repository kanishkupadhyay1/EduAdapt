def normalize_topic_name(topic: str) -> str:
    """Resolve topic name aliases to canonical question bank topic keys."""
    t = (topic or "").strip().lower()
    if "dynamic" in t or "dma" in t or "malloc" in t or "heap" in t:
        return "Dynamic Memory Allocation"
    if "point" in t:
        return "Pointers"
    if "array" in t:
        return "Arrays"
    if "string" in t:
        return "Strings"
    if "struct" in t:
        return "Structures"
    if "func" in t or "recur" in t:
        return "Functions"
    if "loop" in t or "for" in t or "while" in t:
        return "Loops"
    if "cond" in t or "if" in t or "switch" in t:
        return "Conditionals"
    if "op" in t or "expr" in t:
        return "Operators and Expressions"
    if "var" in t or "type" in t or "data" in t:
        return "Variables and Data Types"
    return topic


def get_practice_questions(topic: str, count: int = 5) -> List[Dict[str, Any]]:
    """Retrieve exactly count (5) Practice MCQs for the specified topic."""
    norm_topic = normalize_topic_name(topic)
    questions = PRACTICE_BANK.get(norm_topic) or PRACTICE_BANK.get(topic) or PRACTICE_BANK["Pointers"]
    return questions[:count]


def get_assessment_questions(topic: str, count: int = 10) -> List[Dict[str, Any]]:
    """Retrieve exactly count (10) Assessment MCQs for the specified topic."""
    norm_topic = normalize_topic_name(topic)
    questions = ASSESSMENT_BANK.get(norm_topic) or ASSESSMENT_BANK.get(topic) or ASSESSMENT_BANK["Pointers"]
    return questions[:count]


def verify_topic_zero_intersection(topic: str) -> Tuple[bool, str]:
    """Mathematically verify |P| = 5, |A| = 10, and P ∩ A = ∅ for a given topic."""
    p_set = get_practice_questions(topic, 5)
    a_set = get_assessment_questions(topic, 10)

    if len(p_set) != 5:
        return False, f"Topic '{topic}' practice count is {len(p_set)}, expected exactly 5."

    if len(a_set) != 10:
        return False, f"Topic '{topic}' assessment count is {len(a_set)}, expected exactly 10."

    # 1. Check ID collision
    p_ids = {q["id"] for q in p_set}
    a_ids = {q["id"] for q in a_set}
    id_intersection = p_ids.intersection(a_ids)
    if id_intersection:
        return False, f"Topic '{topic}' has ID intersection: {id_intersection}"

    # 2. Check exact normalized question text collision
    p_texts = {normalize_text(q["question"]) for q in p_set}
    a_texts = {normalize_text(q["question"]) for q in a_set}
    text_intersection = p_texts.intersection(a_texts)
    if text_intersection:
        return False, f"Topic '{topic}' has exact text intersection: {text_intersection}"

    # 3. Check semantic near-duplicate collision (Jaccard similarity threshold 0.65)
    for p_q in p_set:
        for a_q in a_set:
            sim = calculate_jaccard_similarity(p_q["question"], a_q["question"])
            if sim >= 0.65:
                return False, (
                    f"Topic '{topic}' has high semantic similarity ({sim:.2f}) between:\n"
                    f"  Practice: {p_q['question']}\n"
                    f"  Assessment: {a_q['question']}"
                )

    return True, f"Verified: Topic '{topic}' has |P|=5, |A|=10, P intersect A = empty"


def verify_all_topics_zero_intersection() -> Dict[str, Tuple[bool, str]]:
    """Verify zero intersection across all supported PPS topics."""
    results = {}
    for topic in PRACTICE_BANK.keys():
        results[topic] = verify_topic_zero_intersection(topic)
    return results
