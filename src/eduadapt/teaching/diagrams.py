"""Diagram generation, syntax validation, and fallback handlers for EduAdapt.

Validates and sanitizes Mermaid diagram source generated by Mistral 7B.
Ensures malformed diagram code does not crash lessons or display broken UI.
"""

from dataclasses import dataclass
import re
from typing import Any, Dict, List, Optional


VALID_MERMAID_STARTS = (
    "flowchart td",
    "flowchart lr",
    "flowchart rl",
    "flowchart bt",
    "graph td",
    "graph lr",
    "graph rl",
    "graph bt",
    "sequencediagram",
    "classdiagram",
    "statediagram",
    "statediagram-v2",
    "erdiagram",
)


def get_topic_default_mermaid(topic: str = "Pointers") -> str:
    """Return an accurate, valid Mermaid architectural diagram for the specified PPS C topic."""
    t_lower = (topic or "").lower()

    if "dynamic" in t_lower or "dma" in t_lower or "malloc" in t_lower or "heap" in t_lower:
        return (
            "flowchart TD\n"
            "    subgraph StackSpace [\"Stack Memory\"]\n"
            "        Ptr[\"Pointer Variable: int *arr = 0x5000\\n(Size: 8 Bytes)\"]\n"
            "    end\n"
            "    subgraph HeapSpace [\"Heap Memory (Dynamic Allocation)\"]\n"
            "        Block[\"malloc(5 * sizeof(int))\\nContinuous 20-Byte Block (0x5000)\"]\n"
            "        E0[\"arr[0] : 0\"]\n"
            "        E1[\"arr[1] : 0\"]\n"
            "        E4[\"arr[4] : 0\"]\n"
            "    end\n"
            "    Ptr -->|Points to Heap Address| Block\n"
            "    Block --- E0\n"
            "    Block --- E1\n"
            "    Block --- E4\n"
            "    Free[\"Deallocation: free(arr)\"] -->|Releases Heap Block to OS| HeapSpace"
        )
    elif "string" in t_lower:
        return (
            "flowchart LR\n"
            "    subgraph StringArray [\"Character Array: char str[] = 'C Programming'\"]\n"
            "        C0[\"'C'\\nIndex: 0\"]\n"
            "        C1[\"' '\\nIndex: 1\"]\n"
            "        C2[\"'P'\\nIndex: 2\"]\n"
            "        Dots[\"...\\nIndex: 3..12\"]\n"
            "        NullTerm[\"'\\0'\\nIndex: 13 (ASCII: 0)\"]\n"
            "    end\n"
            "    C0 --> C1 --> C2 --> Dots --> NullTerm\n"
            "    NullTerm -->|Signifies String Boundary| End[\"End of String Sentinel\"]"
        )
    elif "point" in t_lower:
        return (
            "flowchart TD\n"
            "    Var[\"Integer Variable: num = 42\\n(Address: 0x1000)\"] --> Cell[\"Memory Cell: [ 42 ]\"]\n"
            "    Ptr[\"Pointer Variable: int *ptr = 0x1000\\n(Address: 0x2000)\"] -->|Stores Address &num| Var\n"
            "    Deref[\"Dereference Operator: *ptr\"] -->|Directly Accesses Value| Cell"
        )
    elif "array" in t_lower:
        return (
            "flowchart LR\n"
            "    subgraph Memory [\"Contiguous Memory Block\"]\n"
            "        E0[\"arr[0] : 10\\nOffset: 0B\"]\n"
            "        E1[\"arr[1] : 20\\nOffset: +4B\"]\n"
            "        E2[\"arr[2] : 30\\nOffset: +8B\"]\n"
            "        E3[\"arr[3] : 40\\nOffset: +12B\"]\n"
            "    end\n"
            "    Base[\"Base Pointer: arr (0x1000)\"] --> E0"
        )
    elif "func" in t_lower or "recur" in t_lower:
        return (
            "flowchart TD\n"
            "    Caller[\"1. main() Caller Frame\"] -->|Pass Parameters by Value/Ref| Stack[\"2. Push Call Stack Frame\"]\n"
            "    Stack -->|Allocate Local Scope| Exec[\"3. Function Execution & Logic\"]\n"
            "    Exec -->|Return Result| Ret[\"4. Return Value & Pop Stack Frame\"]\n"
            "    Ret --> Caller"
        )
    elif "loop" in t_lower or "for" in t_lower or "while" in t_lower:
        return (
            "flowchart TD\n"
            "    Init[\"1. Initialization (int i = 0)\"] --> Cond{\"2. Condition Test (i < N)?\"}\n"
            "    Cond -->|True| Body[\"3. Execute Loop Body Statements\"]\n"
            "    Body --> Step[\"4. Step / Increment (i++)\"]\n"
            "    Step --> Cond\n"
            "    Cond -->|False| Exit[\"5. Terminate Loop and Exit\"]"
        )
    elif "struct" in t_lower:
        return (
            "flowchart TD\n"
            "    subgraph StructLayout [\"struct Student (Sequential Memory Alignment)\"]\n"
            "        F1[\"int id (4 bytes)\"]\n"
            "        F2[\"char name[20] (20 bytes)\"]\n"
            "        F3[\"float gpa (4 bytes)\"]\n"
            "    end\n"
            "    Ptr[\"Pointer: struct Student *s\"] -->|s->id (Arrow Operator)| F1"
        )
    elif "cond" in t_lower or "if" in t_lower or "switch" in t_lower:
        return (
            "flowchart TD\n"
            "    Start[\"Evaluate Condition Expression\"] --> Branch{\"Condition is Non-Zero (True)?\"}\n"
            "    Branch -->|True| PathT[\"Execute if Block Body\"]\n"
            "    Branch -->|False| PathF[\"Execute else / else-if Body\"]\n"
            "    PathT --> Merge[\"Continue Sequential Execution\"]\n"
            "    PathF --> Merge"
        )
    elif "op" in t_lower or "expr" in t_lower:
        return (
            "flowchart TD\n"
            "    Expr[\"C Expression Evaluation\"] --> P1[\"1. Primary / Postfix Operators: (), [], ->, .\"]\n"
            "    P1 --> P2[\"2. Unary Operators: ++, --, *, &, sizeof\"]\n"
            "    P2 --> P3[\"3. Multiplicative & Additive: *, /, %, +, -\"]\n"
            "    P3 --> P4[\"4. Relational & Equality: <, <=, >, >=, ==, !=\"]\n"
            "    P4 --> P5[\"5. Logical Operators: &&, ||\"]\n"
            "    P5 --> P6[\"6. Assignment Operators: =, +=, -=\"]"
        )
    elif "var" in t_lower or "type" in t_lower or "data" in t_lower:
        return (
            "flowchart TD\n"
            "    Types[\"Fundamental C Data Types\"] --> CharT[\"char (1 Byte, -128 to 127)\"]\n"
            "    Types --> IntT[\"int (4 Bytes, -2^31 to 2^31-1)\"]\n"
            "    Types --> FloatT[\"float (4 Bytes, 6-7 Decimal Precision)\"]\n"
            "    Types --> DoubleT[\"double (8 Bytes, 15 Decimal Precision)\"]"
        )
    else:
        return (
            "flowchart TD\n"
            f"    Input[\"Input / Variable Data: {topic}\"] --> Process[\"Execute C Statements & Logic\"]\n"
            "    Process --> Output[\"Program Result / Standard Output\"]"
        )


@dataclass
class DiagramResult:
    """Encapsulates parsed and validated Mermaid diagram metadata."""

    is_valid: bool
    diagram_type: str
    mermaid_code: str
    title: str = "Concept Diagram"
    explanation: str = ""
    validation_error: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "is_valid": self.is_valid,
            "diagram_type": self.diagram_type,
            "mermaid_code": self.mermaid_code,
            "title": self.title,
            "explanation": self.explanation,
            "validation_error": self.validation_error,
        }


class MermaidValidator:
    """Validates and sanitizes educational Mermaid diagram source."""

    @staticmethod
    def extract_mermaid_code(text: str) -> Optional[str]:
        """Extract Mermaid source block from LLM markdown response."""
        blocks = MermaidValidator.extract_all_mermaid_blocks(text)
        return blocks[0] if blocks else None

    @staticmethod
    def extract_all_mermaid_blocks(text: str) -> List[str]:
        """Extract ALL Mermaid source blocks from LLM markdown response."""
        if not text:
            return []

        clean_text = text.replace(r"\n", "\n").replace(r"\r", "")
        blocks: List[str] = []

        # 1. Match explicit ```mermaid ... ``` or ```flowchart ... ``` or ```graph ... ```
        pattern = re.compile(
            r"```(?:mermaid|flowchart|graph)?\s*([\s\S]*?)```",
            re.IGNORECASE,
        )

        for match in pattern.finditer(clean_text):
            body = match.group(1).strip()
            first_line = body.split("\n", 1)[0].strip().lower()
            if any(first_line.startswith(prefix) for prefix in VALID_MERMAID_STARTS) or "-->" in body or "---" in body:
                blocks.append(body)

        # 2. If no fenced blocks found, check if text itself is a diagram
        if not blocks:
            stripped = clean_text.strip()
            first_line = stripped.split("\n", 1)[0].strip().lower()
            if any(first_line.startswith(prefix) for prefix in VALID_MERMAID_STARTS):
                blocks.append(stripped)

        return blocks

    @classmethod
    def validate_and_sanitize_all(
        cls,
        raw_blocks: List[str],
        topic: str = "PPS Concept",
        diagram_type: str = "concept_flowchart",
    ) -> List[DiagramResult]:
        """Validate and sanitize multiple Mermaid diagram blocks independently."""
        results: List[DiagramResult] = []
        if not raw_blocks:
            res = cls.validate_and_sanitize(None, topic=topic, diagram_type=diagram_type)
            results.append(res)
            return results

        diagram_subtitles = [
            f"{topic} Memory & Structural Architecture",
            f"{topic} Execution & State Transition",
            f"{topic} Control Flow & Invariants",
            f"{topic} Runtime Mechanics Overview",
        ]

        for idx, block in enumerate(raw_blocks):
            res = cls.validate_and_sanitize(block, topic=topic, diagram_type=diagram_type)
            title_text = diagram_subtitles[idx] if idx < len(diagram_subtitles) else f"{topic} Architectural Flow {idx + 1}"
            res.title = title_text
            res.explanation = f"Visual representation: {title_text}."
            results.append(res)

        return results

    @classmethod
    def validate_and_sanitize(
        cls,
        raw_mermaid: Optional[str],
        topic: str = "PPS Concept",
        diagram_type: str = "concept_flowchart",
    ) -> DiagramResult:
        """Validate Mermaid code syntax, sanitize malformed syntax, and return a clean DiagramResult."""
        default_fallback = get_topic_default_mermaid(topic)

        if not raw_mermaid or not raw_mermaid.strip():
            return DiagramResult(
                is_valid=False,
                diagram_type=diagram_type,
                mermaid_code="",
                title=f"{topic} Architecture Diagram",
                explanation="",
                validation_error="Diagram source is empty or null.",
            )

        # Check for unclosed/unbalanced bracket delimiters in the input
        if (
            raw_mermaid.count("[") != raw_mermaid.count("]")
            or raw_mermaid.count("(") != raw_mermaid.count(")")
            or raw_mermaid.count("{") != raw_mermaid.count("}")
        ):
            return DiagramResult(
                is_valid=False,
                diagram_type=diagram_type,
                mermaid_code=raw_mermaid.strip(),
                title=f"{topic} Architecture Diagram",
                explanation="",
                validation_error="Unbalanced bracket delimiters in diagram source.",
            )

        # 1. Normalize line breaks and remove escape sequences
        code = raw_mermaid.replace(r"\n", "\n").replace(r"\r", "").strip()

        # 2. Strip accidental code fences
        code = re.sub(r"^```(?:mermaid|flowchart|graph)?", "", code, flags=re.MULTILINE | re.IGNORECASE).strip()
        code = re.sub(r"```$", "", code, flags=re.MULTILINE).strip()

        raw_lines = [line.strip() for line in code.splitlines() if line.strip()]
        if not raw_lines:
            return DiagramResult(
                is_valid=False,
                diagram_type=diagram_type,
                mermaid_code="",
                title=f"{topic} Architecture Diagram",
                explanation="",
                validation_error="Diagram source is empty after stripping fences.",
            )

        # 3. Filter out leaked C code lines (headers, functions, printf)
        sanitized_lines = []
        header_seen = False

        for line in raw_lines:
            line_lower = line.lower()

            # Skip leaked C code statements
            if line.startswith("#include") or line.startswith("int main") or line.startswith("printf(") or line == "return 0;":
                continue
            if line.startswith("void ") and "-->" not in line and "---" not in line:
                continue

            # Check if this line is a diagram header
            is_header = any(line_lower.startswith(prefix) for prefix in VALID_MERMAID_STARTS)

            if is_header:
                if not header_seen:
                    # Keep the first header line (e.g. flowchart TD)
                    sanitized_lines.append(line)
                    header_seen = True
                # Skip duplicate headers
                continue

            # 4. Fix malformed flowchart arrows (e.g. --|> from class diagrams, or --ptr->)
            fixed_line = re.sub(r"--\|>", "-->", line)
            fixed_line = re.sub(r"--[ox]", "-->", fixed_line)
            fixed_line = re.sub(
                r"--\s*([A-Za-z0-9_*&.\- ]+?)\s*->",
                r"-->|\1|",
                fixed_line,
            )

            # 5. Quote unquoted node labels with special characters (brackets, parens, &, *, ->, =, spaces)
            # Example: A[num = 42] -> A["num = 42"]
            def _quote_label(match: re.Match) -> str:
                node_id = match.group(1)
                inner = match.group(2).strip()
                if inner.startswith('"') and inner.endswith('"'):
                    return f"{node_id}[{inner}]"
                clean_inner = inner.replace('"', "'")
                return f'{node_id}["{clean_inner}"]'

            fixed_line = re.sub(
                r'([A-Za-z0-9_]+)\[([^\]\n]+)\]',
                _quote_label,
                fixed_line,
            )

            # 6. Fix unbracketed multi-token node names after arrows, e.g. "Character --> Memory Cell"
            def _fix_unbracketed_node(m: re.Match) -> str:
                arrow = m.group(1)
                target = m.group(2).strip()
                if " " in target and not target.startswith("[") and not target.startswith('"'):
                    clean_id = re.sub(r"[^\w]", "_", target)
                    return f"{arrow} {clean_id}[\"{target}\"]"
                return m.group(0)

            fixed_line = re.sub(
                r"(-->|---|==>|\-\.\->)\s*([A-Za-z0-9_ ]+)(?=$|\n)",
                _fix_unbracketed_node,
                fixed_line,
            )

            sanitized_lines.append(fixed_line)

        # Ensure valid header exists at the top
        if not header_seen:
            sanitized_lines.insert(0, "flowchart TD")

        sanitized_code = "\n".join(sanitized_lines)

        # 6. Syntax validation check: must contain connection operators
        if not re.search(r"-->|---|==>|\-\.\->|\[|\(", sanitized_code) or len(sanitized_lines) <= 1:
            return DiagramResult(
                is_valid=True,
                diagram_type=diagram_type,
                mermaid_code=default_fallback,
                title=f"{topic} Architecture Diagram",
                explanation=f"Visual representation of {topic} mechanics and flow.",
                validation_error=None,
            )

        return DiagramResult(
            is_valid=True,
            diagram_type=diagram_type,
            mermaid_code=sanitized_code,
            title=f"{topic} Architecture Diagram",
            explanation=f"Visual representation of {topic} mechanics and flow.",
            validation_error=None,
        )
